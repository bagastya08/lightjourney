-- Run this once in your Supabase project's SQL editor.

create extension if not exists pgcrypto;

-- One row per client session. Created either by the public booking form
-- (token/quota null until you open it in /admin) or you can add one by hand.
create table if not exists bookings (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  name text not null,
  whatsapp text not null,
  email text,
  session_type text not null,
  preferred_date date not null,
  preferred_time text,
  notes text,
  status text not null default 'new' check (status in ('new', 'confirmed', 'done', 'cancelled')),
  token text unique,
  quota int
);

create table if not exists photos (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  booking_id uuid not null references bookings(id) on delete cascade,
  storage_path text not null,
  filename text not null
);

create table if not exists selections (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  booking_id uuid not null references bookings(id) on delete cascade,
  photo_id uuid not null references photos(id) on delete cascade,
  unique (booking_id, photo_id)
);

alter table bookings enable row level security;
alter table photos enable row level security;
alter table selections enable row level security;
-- No public policies: only the server (service role key) can read/write these tables.
-- The public calendar and /proof/[token] pages go through server API routes, not
-- direct client DB access, so RLS stays fully locked down.

-- Photos come from Google Drive (thumbnail URLs); no Supabase Storage bucket needed.

-- Google Drive source: admin pastes a shared Drive folder link, server lists its
-- images (GOOGLE_API_KEY) and inserts them as photos rows for the client to pick.
-- Safe to re-run on an existing database.
alter table bookings add column if not exists drive_url text;
alter table photos add column if not exists drive_file_id text;
create unique index if not exists photos_booking_drive_file on photos (booking_id, drive_file_id);

-- Newer Supabase projects don't auto-grant new tables to the API roles.
-- Only the server's service_role gets access; anon/authenticated stay locked out.
grant select, insert, update, delete on bookings, photos, selections to service_role;

-- Admin-created projects: title is the public name shown on /foto (null = hidden,
-- so bookings from the public form stay private until you give them a title).
alter table bookings add column if not exists title text;
alter table bookings alter column whatsapp drop not null;

-- Access code: generated by the database on every new booking (public form or admin),
-- 8 chars without look-alikes (0/O, 1/I/L). Only shown on /admin/bookings/[id].
create or replace function gen_access_code() returns text language sql volatile as $$
  select string_agg(substr('ABCDEFGHJKMNPQRSTUVWXYZ23456789', 1 + get_byte(r.b, i) % 31, 1), '')
  from (select extensions.gen_random_bytes(8) as b) r, generate_series(0, 7) as i
$$;
alter table bookings alter column token set default gen_access_code();
alter table bookings alter column quota set default 5;
update bookings set token = gen_access_code() where token is null;
update bookings set quota = 5 where quota is null;
